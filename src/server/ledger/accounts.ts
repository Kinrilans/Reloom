/**
 * Счета леджера.
 *
 * Двойная запись в упрощённом виде: любое движение денег — проводка
 * с двумя и более записями, сумма которых равна нулю.
 *
 * Счетов ровно три вида, и расширять их набор без нужды не надо:
 * чем меньше счетов, тем проще сойтись.
 */

export const FEE_INCOME = 'FEE_INCOME'
export const EXTERNAL = 'EXTERNAL'

/** Счёт пользователя: наше обязательство перед ним. */
export function userAccount(userId: string): string {
  return `USER:${userId}`
}

/** Тип проводки. */
export type LedgerType = 'DEPOSIT' | 'SPEND' | 'REFUND' | 'WITHDRAWAL' | 'ADJUSTMENT'

/**
 * Откуда взялась проводка. Пара «тип источника + идентификатор»
 * уникальна в базе — это и есть защита от двойного зачисления и от
 * повторной доставки события.
 */
export type LedgerSourceType =
  | 'DEPOSIT_REQUEST' // заявка на пополнение; идентификатор — её id
  | 'CHAIN_TX' // транзакция в сети; идентификатор — её хеш
  | 'CARD_TX' // транзакция по карте; идентификатор — UUID эмитента
  | 'WITHDRAWAL' // вывод, оформленный оператором
  | 'ADJUSTMENT' // ручная корректировка
