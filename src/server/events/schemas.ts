/**
 * Схемы событий.
 *
 * Событие — **уведомление, а не запись**. В `data` приходит только
 * разрешённый минимум, и значения там в вокабуляре эмитента, в нижнем
 * регистре, а не в перечислениях REST-чтения. Поэтому схемы здесь
 * нарочно слабые: требуется только то, без чего событие нельзя
 * маршрутизировать.
 *
 * Правильный паттерн: событие говорит, **что перечитать**; действуем
 * по результату чтения. Единственное исключение — суммы авторизации,
 * которые живут только в событии и при чтении затираются.
 */

import { z } from 'zod'

/** Тело вебхука. Идентификатор берём из заголовка; в теле он тоже
 *  может быть, и тогда он обязан совпасть. */
export const webhookBodySchema = z
  .object({
    id: z.string().optional(),
    type: z.string().min(1),
    data: z.unknown().optional(),
  })
  .loose()

/**
 * Данные события о транзакции.
 *
 * Всё необязательно, кроме идентификатора: без него непонятно, что
 * перечитывать. Суммы здесь — целые сотые доли валюты, включая
 * валюты без дробной части.
 */
export const transactionEventDataSchema = z
  .object({
    id: z.string().min(1),
    cardId: z.string().optional(),
    amount: z.coerce.bigint().optional(),
    currency: z.string().optional(),
    localAmount: z.coerce.bigint().optional(),
    localCurrency: z.string().optional(),
    merchantName: z.string().optional(),
    occurredAt: z.string().optional(),
  })
  .loose()

/** Данные события о карте. Несёт только текущий статус — в нижнем
 *  регистре. Сравнивать его с перечислением чтения нельзя. */
export const cardEventDataSchema = z
  .object({
    id: z.string().min(1),
    status: z.string().optional(),
  })
  .loose()

