/**
 * Что из события можно хранить.
 *
 * Событие `challenge.requested` несёт **одноразовый пароль** для
 * подтверждения оплаты. Одноразовые коды не логируются и не хранятся
 * ни в каком виде (CLAUDE.md, правило 7; `docs/security.md`).
 *
 * Поэтому у таких событий тело в базу не попадает вовсе. Хранится
 * факт: событие было, такого типа, в такое время. Этого достаточно
 * для очереди, для дедупликации и для разбора; код для доставки
 * берётся из живого вебхука, а не из базы.
 *
 * Выборочная зачистка полей здесь не годится. Их имена не
 * подтверждены, набор может поменяться вместе с контрактом, и одно
 * незачищенное поле означает пароль, лежащий в базе и в дампах.
 * Отсутствие тела такой ошибки не допускает в принципе.
 *
 * Отдельно: код, пришедший догоном, всё равно просрочен — у него
 * короткий срок жизни. Хранить его не только опасно, но и незачем.
 */

/** События, тело которых не хранится никогда. */
const SECRET_BEARING = new Set(['challenge.requested'])

export function isSecretBearing(type: string): boolean {
  return SECRET_BEARING.has(type)
}

export function redactForStorage(type: string, data: unknown): unknown {
  return isSecretBearing(type) ? { redacted: true } : data
}
