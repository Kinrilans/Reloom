/**
 * Zod-схема ответа сервиса проверки происхождения.
 *
 * Формат не подтверждён: документации сервиса в проекте нет, доступа
 * к API пока нет. Поэтому требуется минимум — оценка риска, — а всё
 * непроверенное собрано в `UNVERIFIED`.
 */

import { z } from 'zod'

export const screeningSchema = z
  .object({
    // Оценку мы не считаем: она приходит готовой и только сравнивается
    // с порогом из настроек.
    risk: z.coerce.number(),
    reference: z.string().optional(),
  })
  .loose()

export const errorBodySchema = z
  .object({
    code: z.string().optional(),
    message: z.string().optional(),
    retryAfterSeconds: z.coerce.number().optional(),
  })
  .loose()

