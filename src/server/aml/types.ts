/**
 * Интерфейс адаптера проверки происхождения средств.
 *
 * Одна операция и один принцип: **оценку риска мы не считаем.** Она
 * приходит готовой от сервиса, а мы только сравниваем её с порогом из
 * настроек админки. Любая арифметика над риском здесь была бы нашим
 * собственным скорингом, которого мы не умеем и не обещали.
 */

import type { Minor } from '@/shared/money'

/**
 * Исход проверки.
 *
 * Три состояния, и смешивать их нельзя. «Не прошло» означает, что
 * сервис ответил и оценка высокая, — деньги удерживаются и предлагается
 * возврат. «Сервис не ответил» не говорит о деньгах ничего: по
 * умолчанию поступление ждёт оператора, а зачислять ли его без
 * проверки — переключатель в админке, выключенный осознанно.
 */
export type AmlVerdict = 'PASSED' | 'FAILED' | 'UNAVAILABLE'

export interface AmlScreening {
  verdict: AmlVerdict
  /** Оценка риска от сервиса. Нет при `UNAVAILABLE`. */
  risk: number | undefined
  /** Почему сервис не дал ответа. Только при `UNAVAILABLE`. */
  unavailableReason: string | undefined
  /** Их идентификатор проверки — для журнала обмена и разбора. */
  reference: string | undefined
}

export interface AmlRequest {
  /** Транзакция в сети: по ней сервис и смотрит происхождение. */
  chainTxId: string
  network: string
  asset: string
  amountMinor: Minor
  /** Адрес отправителя, если сеть его отдала. */
  fromAddress: string | undefined
}

export interface AmlClient {
  /**
   * Проверить поступление.
   *
   * Недоступность сервиса **не бросается исключением**: это штатный
   * исход, у которого есть своя ветка поведения. А вот неверный ключ
   * или испорченный запрос бросаются: это наша ошибка, и прятать её
   * за «сервис недоступен» значит тихо остановить зачисления по всей
   * платформе без объяснения причины.
   */
  screen(input: AmlRequest): Promise<AmlScreening>
}
